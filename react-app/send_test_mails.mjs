async function sendSubmissions() {
  console.log(`Starting dispatch of ${testSubmissions.length} test submissions to ${endpoint}...\n`);
  
  for (let i = 0; i < testSubmissions.length; i++) {
    const item = testSubmissions[i];
    console.log(`[${i + 1}/${testSubmissions.length}] Sending "${item["Brand / Company"]}" for ${item["Client Name"]}...`);
    
    try {
      const res = await fetch(endpoint, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "Accept": "application/json",
          "Origin": "http://localhost:3004",
          "Referer": "http://localhost:3004/brand-readiness"
        },
        body: JSON.stringify(item)
      });
      
      const data = await res.json();
      console.log(` -> Status ${res.status}:`, data);
    } catch (err) {
      console.error(` -> Error sending submission ${i + 1}:`, err.message);
    }
    
    if (i < testSubmissions.length - 1) {
      console.log("Waiting 2.5s before next submission...\n");
      await new Promise(r => setTimeout(r, 2500));
    }
  }
  
  console.log("\nAll 5 test submissions dispatched successfully!");
}

